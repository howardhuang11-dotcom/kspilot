"""Experiment report for the write-up: logs/experiments.jsonl -> docs/EXPERIMENTS.md (table + per-config stats).

usage: exp_report.py            (rewrites docs/EXPERIMENTS.md)
"""
import json
import os
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "logs", "experiments.jsonl")
OUT = os.path.join(ROOT, "docs", "EXPERIMENTS.md")


def config_key(r):
    p = r.get("params", {})
    return "%s; fins=%s; glide tmin %s, max %s deg, below %s m; start %s" % (
        r.get("craft"), p.get("has_fins"), p.get("glide_tmin"), p.get("glide_max_deg"), p.get("glide_below"),
        r.get("start"))


def main():
    rows = [json.loads(l) for l in open(SRC)] if os.path.exists(SRC) else []
    groups = defaultdict(list)
    for r in rows:
        groups[config_key(r)].append(r)
    out = ["# Flight experiments (auto-generated by tools/exp_report.py)", "",
           "Every flight appends one record to `logs/experiments.jsonl` (config, git revision, ignition state, outcome).", "",
           "## Summary by configuration", "",
           "| configuration | flights | success | bullseye (<2 m) | median miss (m) | median touchdown (m/s) |",
           "|---|---|---|---|---|---|"]
    for k, rs in groups.items():
        miss = sorted(r["result"]["miss"] for r in rs)
        vtd = sorted(r["result"]["v_td"] for r in rs)
        ok = sum(r["result"]["ok"] for r in rs)
        bull = sum(r["result"]["ok"] and r["result"]["miss"] < 2 for r in rs)
        out.append("| %s | %d | %d | %d | %.1f | %.2f |" % (k, len(rs), ok, bull, miss[len(miss) // 2], vtd[len(vtd) // 2]))
    out += ["", "## All flights", "",
            "| time | git | craft | start | ignition h / offset | miss (m) | v_td (m/s) | upright | fuel | ok |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        ig = r.get("ignition") or {}
        res = r["result"]
        out.append("| %s | %s | %s | %s | %s / %s | %.1f | %.2f | %.2f | %.0f | %s |" % (
            r["time"], r.get("git"), r.get("craft"), r.get("start"), ig.get("h", "-"), ig.get("offset", "-"),
            res["miss"], res["v_td"], res["upright"], res["fuel_left"], "PASS" if res["ok"] else "FAIL"))
    open(OUT, "w").write("\n".join(out) + "\n")
    print("wrote", OUT, "with", len(rows), "flights in", len(groups), "configurations")


if __name__ == "__main__":
    main()
